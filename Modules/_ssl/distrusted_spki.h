/* Denylist of distrusted SubjectPublicKeyInfo (SPKI).
 *
 * Verification rejects any chain with a cert whose SPKI (DER-encoded
 * SubjectPublicKeyInfo) is in the _distrusted_spki table.  We match the key,
 * not a cert fingerprint, so cross-signs that reuse the key are blocked too.
 * To block another key, add its SPKI DER and a table entry.
 *
 * Dump a cert's SPKI DER and its SHA-256 with OpenSSL:
 *
 *     $ openssl x509 -in cert.pem -noout -pubkey | openssl pkey -pubin -outform DER > spki.der
 *     $ xxd -i spki.der
 *     $ openssl dgst -sha256 spki.der
 */
