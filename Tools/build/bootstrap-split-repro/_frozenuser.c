/* Reproducer: a user builtin module (via Modules/Setup.local) whose source
   includes a header generated by the build's own freeze tooling
   (Programs/_freeze_module). On main this is a dependency cycle:
   _freeze_module links every static module object, including this one. */

#include "Python.h"
#include "marshal.h"

#include "_frozenuser_data.h"    // _Py_M___frozenuser[] (generated)

static PyObject *
frozenuser_code(PyObject *module, PyObject *Py_UNUSED(args))
{
    return PyMarshal_ReadObjectFromString(
        (const char *)_Py_M___frozenuser, sizeof(_Py_M___frozenuser));
}

static PyMethodDef methods[] = {
    {"code", frozenuser_code, METH_NOARGS, NULL},
    {NULL, NULL, 0, NULL},
};

static struct PyModuleDef moduledef = {
    PyModuleDef_HEAD_INIT, "_frozenuser", NULL, 0, methods,
};

PyMODINIT_FUNC
PyInit__frozenuser(void)
{
    return PyModuleDef_Init(&moduledef);
}
