"""Emit a complete C parser from an immutable plan and local output state."""

import pathlib
from collections.abc import Iterator
from contextlib import contextmanager
from typing import IO

from pegen.c_generator_model import CParser, CRule
from pegen.c_generator_rules import CRuleEmitter

SHARED_RULE_PREFIX = "_PyPegen_"


class CParserEmitter:
    def __init__(self, parser: CParser, file: IO[str] | None, source: pathlib.Path | None = None):
        self._parser = parser
        self._file = file
        self._source = source
        self._level = 0

    def emit(self) -> None:
        self._emit_headers()
        if self._source is None:
            self._emit_keywords()
        self._emit_declarations()
        self._emit_rules()
        if self._source is None and self._parser.trailer is not None:
            self.print(self._parser.trailer)

    def _own_rules(self) -> Iterator[tuple[int, CRule]]:
        # Rule type ids number all rules of the parser, so that they stay
        # unique across its C files.
        for rule_id, rule in enumerate(self._parser.rules, 1000):
            if rule.source == self._source:
                yield rule_id, rule

    def _emit_headers(self) -> None:
        if self._source is None:
            source_name = self._parser.source_name
        else:
            source_name = self._source.name
        self.print(f"// @generated by pegen from {source_name}")
        for header in self._parser.headers:
            self.print(header)

    def _emit_keywords(self) -> None:
        groups = self._parser.keyword_groups
        self.print(f"static const int n_keyword_lists = {len(groups)};")
        self.print("static KeywordToken *reserved_keywords[] = {")
        with self.indent():
            for group in groups or ((),):
                if not group:
                    self.print("(KeywordToken[]) {{NULL, -1}},")
                else:
                    self.print("(KeywordToken[]) {")
                    with self.indent():
                        for keyword, token_type in group:
                            self.print(f'{{"{keyword}", {token_type}}},')
                        self.print("{NULL, -1},")
                    self.print("},")
        self.print("};")
        self.print("static char *soft_keywords[] = {")
        with self.indent():
            for keyword in self._parser.soft_keywords:
                self.print(f'"{keyword}",')
            self.print("NULL,")
        self.print("};")

    def _emit_declarations(self) -> None:
        for rule_id, rule in self._own_rules():
            comment = "  // Left-recursive" if rule.left_recursive else ""
            self.print(f"#define {rule.signature.name}_type {rule_id}{comment}")
        self.print()
        shared_rules = [rule for rule in self._parser.rules if rule.shared]
        if shared_rules:
            self.print("// Rules shared between the C files of this parser")
            for rule in shared_rules:
                name = f"{rule.signature.name}_rule"
                self.print(f"#define {name} {SHARED_RULE_PREFIX}{name}")
                self.print(f"Py_LOCAL_SYMBOL {rule.signature.declaration(static=False)}")
            self.print()
        for _, rule in self._own_rules():
            if not rule.shared:
                self.print(rule.signature.declaration())
        self.print()

    def _emit_rules(self) -> None:
        for _, rule in self._own_rules():
            self.print()
            if rule.left_recursive:
                self.print("// Left-recursive")
            CRuleEmitter(self, rule, debug=self._parser.debug).emit()

    def print(self, *args: object) -> None:
        if not args:
            print(file=self._file)
        else:
            print("    " * self._level, end="", file=self._file)
            print(*args, file=self._file)

    @contextmanager
    def indent(self) -> Iterator[None]:
        self._level += 1
        try:
            yield
        finally:
            self._level -= 1
